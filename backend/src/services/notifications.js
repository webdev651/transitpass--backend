'use strict';
/*
  Notification management for administrators.

  Students: a message is written to email_log (their portal inbox, and real e-mail when EMAIL_MODE=smtp) and tracked in
  `notifications`; read state and delivery status are read back from email_log, so nothing is duplicated.
  Drivers: the message lives in `notifications` (read by the driver through /api/driver/notifications).
  Automatic reminders (QR code / discount expiring) are generated by generateExpiryNotifications and are never sent twice
  (dedupe_key).
*/
const config = require('../config');
const { notFound, badRequest } = require('../lib/httpError');
const { sendEmail } = require('../lib/email');
const { escapeLike } = require('../lib/sql');
const { toDate } = require('../lib/time');
const { parseValidUntil } = require('../lib/studentStatus');
const settings = require('./settings');
const qr = require('./qr');

const CATEGORIES = ['account_status', 'eligibility_expiry', 'qr_expiry', 'announcement', 'refund', 'general'];
const iso = (v) => (v ? toDate(v).toISOString() : null);
const by = (admin) => (admin ? { id: admin.id, name: admin.name } : { id: null, name: null });

/** One notification to one student. Returns the notifications.id, or null when it was a duplicate. */
async function notifyStudent(pool, student, { category = 'general', title, body, admin = null, dedupeKey = null, announcementId = null, inbox = true }) {
  if (dedupeKey) {
    const [dup] = await pool.query('SELECT id FROM notifications WHERE dedupe_key = ?', [dedupeKey]);
    if (dup.length) return null;
  }
  const emailLogId = inbox && !announcementId ? await sendEmail(pool, student, title, body, { track: false }) : null;
  const a = by(admin);
  try {
    const [res] = await pool.query(
      `INSERT INTO notifications (recipient_type, student_id, recipient_name, category, title, body, delivery_status, email_log_id, announcement_id, dedupe_key, created_by, created_by_name)
       VALUES ('student', ?, ?, ?, ?, ?, 'delivered', ?, ?, ?, ?, ?)`,
      [student.id, student.name, category, title.slice(0, 200), body, emailLogId, announcementId, dedupeKey, a.id, a.name]);
    return res.insertId;
  } catch (e) { if (e.code === 'ER_DUP_ENTRY') return null; throw e; }
}

async function notifyDriver(pool, driver, { category = 'general', title, body, admin = null, dedupeKey = null, announcementId = null }) {
  const a = by(admin);
  try {
    const [res] = await pool.query(
      `INSERT INTO notifications (recipient_type, driver_id, recipient_name, category, title, body, delivery_status, announcement_id, dedupe_key, created_by, created_by_name)
       VALUES ('driver', ?, ?, ?, ?, ?, 'delivered', ?, ?, ?, ?)`,
      [driver.id, driver.name, category, title.slice(0, 200), body, announcementId, dedupeKey, a.id, a.name]);
    return res.insertId;
  } catch (e) { if (e.code === 'ER_DUP_ENTRY') return null; throw e; }
}

/** Account-status messages are skipped when the administrator switched that notification type off in Settings. */
async function accountStatus(pool, target, kind, { title, body, admin = null }) {
  if (!(await settings.get(pool, 'notifications.accountStatus'))) return null;
  return kind === 'driver' ? notifyDriver(pool, target, { category: 'account_status', title, body, admin }) : notifyStudent(pool, target, { category: 'account_status', title, body, admin });
}

const SELECT = `SELECT n.*, el.is_read AS mail_read, el.status AS mail_status, (ar.student_id IS NOT NULL) AS ann_read
                  FROM notifications n
                  LEFT JOIN email_log el ON el.id = n.email_log_id
                  LEFT JOIN announcement_reads ar ON ar.announcement_id = n.announcement_id AND ar.student_id = n.student_id`;

function present(r) {
  const read = r.recipient_type === 'driver' ? !!r.is_read : r.email_log_id ? !!r.mail_read : r.announcement_id ? !!r.ann_read : !!r.is_read;
  // delivery: students with real e-mail on report the mail result; "logged" means placed in the portal inbox only.
  let delivery = r.delivery_status;
  if (r.email_log_id && r.mail_status) delivery = r.mail_status === 'failed' ? 'failed' : 'delivered';
  return {
    id: r.id, recipientType: r.recipient_type, recipient: r.recipient_name, studentId: r.student_id, driverId: r.driver_id,
    category: r.category, title: r.title, body: r.body, read, delivery, channel: r.email_log_id ? (r.mail_status === 'sent' ? 'inbox + email' : 'inbox') : 'inbox',
    announcementId: r.announcement_id, automatic: !r.created_by_name, sentBy: r.created_by_name || 'System', createdAt: iso(r.created_at)
  };
}

async function list(pool, { recipientType, category, read, delivery, q, limit, offset }) {
  const where = [];
  const args = [];
  if (recipientType && recipientType !== 'all') { where.push('n.recipient_type = ?'); args.push(recipientType); }
  if (category && category !== 'all') { where.push('n.category = ?'); args.push(category); }
  if (q) { const like = `%${escapeLike(q)}%`; where.push('(n.recipient_name LIKE ? OR n.title LIKE ? OR n.body LIKE ?)'); args.push(like, like, like); }
  const readExpr = "(CASE WHEN n.recipient_type = 'driver' THEN n.is_read WHEN n.email_log_id IS NOT NULL THEN el.is_read WHEN n.announcement_id IS NOT NULL THEN (ar.student_id IS NOT NULL) ELSE n.is_read END)";
  if (read === 'read') where.push(`${readExpr} = 1`);
  if (read === 'unread') where.push(`${readExpr} = 0`);
  if (delivery === 'failed') where.push("(n.delivery_status = 'failed' OR el.status = 'failed')");
  if (delivery === 'delivered') where.push("(n.delivery_status = 'delivered' AND (el.status IS NULL OR el.status <> 'failed'))");
  const clause = where.length ? `WHERE ${where.join(' AND ')}` : '';
  const joins = 'FROM notifications n LEFT JOIN email_log el ON el.id = n.email_log_id LEFT JOIN announcement_reads ar ON ar.announcement_id = n.announcement_id AND ar.student_id = n.student_id';
  const [[{ total }]] = await pool.query(`SELECT COUNT(*) AS total ${joins} ${clause}`, args);
  const [rows] = await pool.query(`${SELECT} ${clause} ORDER BY n.created_at DESC, n.id DESC LIMIT ? OFFSET ?`, [...args, limit, offset]);
  return { total: Number(total), items: rows.map(present) };
}

async function stats(pool) {
  const [[t]] = await pool.query(
    `SELECT COUNT(*) AS total, COALESCE(SUM(n.recipient_type = 'student'), 0) AS students, COALESCE(SUM(n.recipient_type = 'driver'), 0) AS drivers,
            COALESCE(SUM(n.delivery_status = 'failed' OR el.status = 'failed'), 0) AS failed,
            COALESCE(SUM(NOT (CASE WHEN n.recipient_type = 'driver' THEN n.is_read WHEN n.email_log_id IS NOT NULL THEN el.is_read WHEN n.announcement_id IS NOT NULL THEN (ar.student_id IS NOT NULL) ELSE n.is_read END)), 0) AS unread
       FROM notifications n LEFT JOIN email_log el ON el.id = n.email_log_id LEFT JOIN announcement_reads ar ON ar.announcement_id = n.announcement_id AND ar.student_id = n.student_id`);
  return { total: Number(t.total), students: Number(t.students), drivers: Number(t.drivers), failed: Number(t.failed), unread: Number(t.unread) };
}

/** Manual message from an administrator to chosen students / drivers / everyone of one kind. */
async function send(pool, admin, { audience, studentIds = [], driverIds = [], category = 'general', title, body }) {
  let sent = 0;
  if (audience === 'students' || audience === 'selected_students') {
    const [rows] = audience === 'students' ? await pool.query('SELECT * FROM students') : await pool.query('SELECT * FROM students WHERE id IN (?)', [studentIds.length ? studentIds : ['']]);
    if (audience === 'selected_students' && rows.length !== new Set(studentIds).size) throw badRequest('One or more selected students do not exist.');
    for (const s of rows) if (await notifyStudent(pool, s, { category, title, body, admin })) sent++;
  } else {
    const [rows] = audience === 'drivers'
      ? await pool.query("SELECT * FROM admins WHERE role = 'driver' AND status = 'active'")
      : await pool.query("SELECT * FROM admins WHERE role = 'driver' AND id IN (?)", [driverIds.length ? driverIds : [0]]);
    if (audience === 'selected_drivers' && rows.length !== new Set(driverIds).size) throw badRequest('One or more selected drivers do not exist.');
    for (const d of rows) if (await notifyDriver(pool, d, { category, title, body, admin })) sent++;
  }
  return { sent };
}

/**
 * Reminders that nobody has to remember to send: QR codes about to expire and student discounts about to lapse.
 * Safe to call repeatedly (every reminder carries a dedupe_key, so it is created once per QR code / validity date).
 */
async function generateExpiryNotifications(pool, now = new Date()) {
  const qrDays = await settings.get(pool, 'notifications.qrDays');
  const eligDays = await settings.get(pool, 'notifications.eligibilityDays');
  let qrCount = 0;
  let eligCount = 0;
  const [qrs] = await pool.query(
    `SELECT q.id AS qr_id, q.expires_at, s.* FROM qr_codes q JOIN students s ON s.id = q.student_id
      WHERE q.status = 'active' AND q.expires_at > ? AND q.expires_at <= ?`, [now, new Date(now.getTime() + qrDays * 86400000)]);
  for (const r of qrs) {
    const left = Math.max(1, Math.ceil((toDate(r.expires_at).getTime() - now.getTime()) / 86400000));
    const made = await notifyStudent(pool, r, {
      category: 'qr_expiry', dedupeKey: `qrexp:${r.qr_id}`, title: 'Your QR code expires soon',
      body: `Hi ${r.name}, your TransitPass QR code expires in ${left} day${left === 1 ? '' : 's'}. Open My QR Code to generate a new one before it stops working.`
    });
    if (made) qrCount++;
  }
  const [studs] = await pool.query(
    "SELECT * FROM students WHERE status = 'active' AND discount_eligible = 1 AND valid_until REGEXP '^[0-9]{1,2} [A-Za-z]{3,9} [0-9]{4}$'");
  for (const s of studs) {
    const until = parseValidUntil(s.valid_until);
    if (!until) continue;
    const left = Math.ceil((until.getTime() - now.getTime()) / 86400000);
    if (left < 0 || left > eligDays) continue;
    // Same wording as the student portal's own reminder, so a student never gets the same warning twice.
    const subject = 'Your student discount expires soon';
    const [dup] = await pool.query('SELECT 1 FROM email_log WHERE student_id = ? AND subject = ? AND body LIKE ? LIMIT 1', [s.id, subject, `%${escapeLike(s.valid_until)}%`]);
    if (dup.length) continue;
    const made = await notifyStudent(pool, s, {
      category: 'eligibility_expiry', dedupeKey: `elig:${s.id}:${s.valid_until}`.slice(0, 120), title: subject,
      body: `Hi ${s.name}, your student discount is valid until ${s.valid_until} (${Math.max(left, 0)} day${left === 1 ? '' : 's'} left). Open Discount Eligibility to request a renewal before it expires.`
    });
    if (made) eligCount++;
  }
  return { qrExpiry: qrCount, eligibilityExpiry: eligCount };
}

/** Marks QR codes whose time ran out as "expired" and tells each affected student once (dedupe_key per code). */
async function expireAndNotify(pool, now = new Date()) {
  const expired = await qr.expireDue(pool, now);
  let notified = 0;
  for (const q of expired) {
    const [s] = await pool.query('SELECT * FROM students WHERE id = ?', [q.student_id]);
    if (!s[0]) continue;
    const made = await notifyStudent(pool, s[0], {
      category: 'qr_expiry', dedupeKey: `qrexpired:${q.id}`,
      title: 'Your QR code has expired',
      body: `Hi ${s[0].name}, your TransitPass QR code (School ID ${s[0].school_id}) expired and can no longer be scanned. Generate a new one in My QR Code once your pass is active again.`
    });
    if (made) notified++;
  }
  return { expired: expired.length, notified };
}

/* ---- driver inbox (what a signed-in driver sees). Every query is pinned to driver_id = the signed-in driver. ---- */
async function driverInbox(pool, driverId, { limit = 50, offset = 0, unreadOnly = false, filter = 'all', category = 'all' } = {}) {
  const f = unreadOnly ? 'unread' : filter;
  const where = ['driver_id = ?'];
  const args = [driverId];
  if (f === 'unread') where.push('is_read = 0');
  if (f === 'read') where.push('is_read = 1');
  if (category && category !== 'all') { where.push('category = ?'); args.push(category); }
  const clause = where.join(' AND ');
  const [rows] = await pool.query(`SELECT * FROM notifications WHERE ${clause} ORDER BY created_at DESC, id DESC LIMIT ? OFFSET ?`, [...args, limit, offset]);
  const [[t]] = await pool.query(`SELECT COUNT(*) AS n FROM notifications WHERE ${clause}`, args);
  const counts = await driverCounts(pool, driverId);
  return { items: rows.map((r) => ({ ...present(r), readAt: iso(r.read_at) })), total: Number(t.n), unread: counts.unread, read: counts.read, all: counts.all };
}
/** The notification counter: how many the driver has, and how many are unread. */
async function driverCounts(pool, driverId) {
  const [[c]] = await pool.query('SELECT COUNT(*) AS n, COALESCE(SUM(is_read = 0), 0) AS unread FROM notifications WHERE driver_id = ?', [driverId]);
  return { all: Number(c.n), unread: Number(c.unread), read: Number(c.n) - Number(c.unread) };
}
async function driverMarkRead(pool, driverId, id) {
  // own rows only; marking an already-read one again keeps its first read time
  const [r] = await pool.query('UPDATE notifications SET is_read = 1, read_at = COALESCE(read_at, ?) WHERE id = ? AND driver_id = ?', [new Date(), id, driverId]);
  if (!r.affectedRows) throw notFound('Notification not found');
}
async function driverMarkAllRead(pool, driverId) {
  const [r] = await pool.query('UPDATE notifications SET is_read = 1, read_at = ? WHERE driver_id = ? AND is_read = 0', [new Date(), driverId]);
  return { marked: r.affectedRows };
}

